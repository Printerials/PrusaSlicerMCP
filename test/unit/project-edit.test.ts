import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, before, test } from "node:test";
import { serializeValue, setConfigValues, writeProject } from "../../src/formats/project-edit.ts";
import { readProject } from "../../src/formats/threemf.ts";
import { ZipReader } from "../../src/formats/zip.ts";
import { writeZip } from "../helpers/zip.ts";

let dir: string;
before(async () => {
  dir = await mkdtemp(join(tmpdir(), "prusaslicer-mcp-test-"));
});
after(async () => {
  await rm(dir, { recursive: true, force: true });
});

const CONFIG = "; generated by PrusaSlicer 2.9.7\n; fill_density = 15%\n; fill_pattern = grid\n; start_gcode = G28\\nG1 Z5\n";

test("values in PrusaSlicer's serialization", () => {
  assert.equal(serializeValue(true), "1");
  assert.equal(serializeValue(false), "0");
  assert.equal(serializeValue(2), "2");
  assert.equal(serializeValue("10%"), "10%");
  assert.equal(serializeValue("M600\nG1 E0.3"), "M600\\nG1 E0.3");
});

test("config values are replaced in place, new keys appended", () => {
  const next = setConfigValues(CONFIG, new Map([["fill_pattern", "lightning"], ["infill_every_layers", "2"]]));
  assert.equal(next, "; generated by PrusaSlicer 2.9.7\n; fill_density = 15%\n; fill_pattern = lightning\n; start_gcode = G28\\nG1 Z5\n; infill_every_layers = 2\n");
});

test("writeProject copies every entry and replaces only the config", async () => {
  const input = join(dir, "in.3mf");
  const output = join(dir, "out.3mf");
  const mesh = Buffer.alloc(200_000, 7);
  await writeZip(input, {
    "3D/3dmodel.model": '<model><metadata name="Title">t</metadata></model>',
    "Metadata/Slic3r_PE.config": `${CONFIG}; printer_settings_id = P\n; print_settings_id = Q\n; filament_settings_id = "F"\n`,
    "Metadata/Slic3r_PE_model.config": '<config><object id="1"><metadata type="object" key="name" value="a"/></object></config>',
    "3D/mesh.bin": mesh,
  });
  await writeProject(input, output, setConfigValues(CONFIG, new Map([["fill_density", "10%"]])));

  const zip = await ZipReader.open(output);
  try {
    assert.deepEqual([...zip.entries.keys()].sort(), ["3D/3dmodel.model", "3D/mesh.bin", "Metadata/Slic3r_PE.config", "Metadata/Slic3r_PE_model.config"]);
    assert.ok((await zip.read("3D/mesh.bin"))!.equals(mesh), "a copied entry must stay byte for byte");
    assert.match((await zip.readText("Metadata/Slic3r_PE.config"))!, /; fill_density = 10%/);
  } finally {
    await zip.close();
  }
  const project = await readProject(output);
  assert.equal(project.config.get("fill_density"), "10%");
  assert.equal(project.objects[0]?.name, "a");
  await assert.rejects(writeProject(input, output, CONFIG), /EEXIST/, "never writes over an existing file");
});
