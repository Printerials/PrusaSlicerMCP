import assert from "node:assert/strict";
import { chmod, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { runPostProcess, scriptFailure, scriptsOf } from "../../src/slicer/post-process.ts";

const posix = process.platform !== "win32";

test("scriptsOf splits items into lines and drops empty ones, as 2.9.7 does", () => {
  assert.deepEqual(scriptsOf(["/a/one.sh --x", "  /a/two.sh\n\n/a/three.sh  ", ""]), ["/a/one.sh --x", "/a/two.sh", "/a/three.sh"]);
  assert.deepEqual(scriptsOf("/a/one.sh\r\n/a/two.sh"), ["/a/one.sh", "/a/two.sh"]);
  assert.deepEqual(scriptsOf(undefined), []);
  assert.deepEqual(scriptsOf([]), []);
});

test("scriptFailure finds 2.9's report in its log (2.9.7, measured)", () => {
  const log =
    "10 => Processing triangulated mesh\n" +
    "[2026-11-23 11:11:54.424682] [0x000000020c9d9300] [error]   Post-processing script /p/fail.sh on file /p/out/cube.gcode failed.\n" +
    "Error code: 3\nOutput:\nsomething went wrong\n\n";
  assert.equal(scriptFailure(log), "Post-processing script /p/fail.sh on file /p/out/cube.gcode failed.\nError code: 3\nOutput:\nsomething went wrong");
  assert.equal(scriptFailure("90 => Exporting G-code\nSlicing result exported to /p/out/cube.gcode\n"), null);
});

test("runPostProcess: arguments, environment, changes in place; a rename request is reported, not applied", { skip: !posix }, async () => {
  const dir = await mkdtemp(join(tmpdir(), "psmcp-pp-"));
  try {
    // A path with a space and a quote, which the shell must get as one argument.
    const out = join(dir, "it's here");
    await mkdir(out);
    const gcode = join(out, "cube.gcode");
    await writeFile(gcode, "; generated by PrusaSlicer\nG1 X1\n");
    const script = join(dir, "pp.sh");
    await writeFile(
      script,
      [
        "#!/bin/sh",
        "for g; do :; done",
        `printf '%s|%s|%s|%s|%s\\n' "$#" "$1" "$SLIC3R_PP_HOST" "$SLIC3R_PP_OUTPUT_NAME" "$SLIC3R_LAYER_HEIGHT" > "${join(dir, "seen.txt")}"`,
        'echo "; post-processed" >> "$g"',
        'echo "talk on stdout"',
        'echo "renamed.gcode" > "$g.output_name"',
        "",
      ].join("\n"),
    );
    await chmod(script, 0o755);
    const config = new Map([["layer_height", "0.2"], ["fill_density", "15%"], ["named.inner", "x"]]);
    const result = await runPostProcess([`${script} 'two words'`], gcode, config);
    assert.equal(result.renameAsked, "renamed.gcode");
    assert.equal(existsSync(`${gcode}.output_name`), false);
    assert.equal(await readFile(join(dir, "seen.txt"), "utf8"), `2|two words|File|${gcode}|0.2\n`);
    assert.match(await readFile(gcode, "utf8"), /G1 X1\n; post-processed\n$/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test("runPostProcess: a failing script and a G-code that is gone are errors", { skip: !posix }, async () => {
  const dir = await mkdtemp(join(tmpdir(), "psmcp-pp-"));
  try {
    const gcode = join(dir, "cube.gcode");
    await writeFile(gcode, "G1 X1\n");
    const fail = join(dir, "fail.sh");
    await writeFile(fail, "#!/bin/sh\necho 'something went wrong' >&2\nexit 3\n");
    const gone = join(dir, "gone.sh");
    await writeFile(gone, '#!/bin/sh\nfor g; do :; done\nmv "$g" "$g.moved"\n');
    await chmod(fail, 0o755);
    await chmod(gone, 0o755);
    await assert.rejects(runPostProcess([fail], gcode, new Map()), (error: Error) => {
      assert.equal(error.message, `Post-processing script ${fail} on file ${gcode} failed.\nError code: 3\nOutput:\nsomething went wrong`);
      return true;
    });
    // Scripts after a failing one do not run.
    const marker = join(dir, "ran");
    await assert.rejects(runPostProcess([fail, `touch '${marker}'`], gcode, new Map()));
    assert.equal(existsSync(marker), false);
    await assert.rejects(runPostProcess([gone], gcode, new Map()), /expected to change the G-code .* in place/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
