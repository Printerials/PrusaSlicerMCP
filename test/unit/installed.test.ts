import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, before, test } from "node:test";
import { escapeVariants, parseInstalled, parseVariants, readBundles, writeInstalled } from "../../src/slicer/installed.ts";

const APP_INI = `# generated by PrusaSlicer 2.9.7 on 2026-11-14 at 12:11:22 UTC
alert_when_supports_needed = 1
version = 2.9.7

[filaments]
Generic PETG @COREONE HF0.4 = 1
Prusament PLA @COREONE HF0.4 = 1

[presets]
filament = Generic PETG @COREONE HF0.4
printer = Prusa CORE One HF0.4 nozzle

[recent_projects]
1 = /tmp/a.3mf

[vendor:PrusaResearch]
model:COREONE = HF0.4
`;

let dir: string;
before(async () => {
  dir = await mkdtemp(join(tmpdir(), "prusaslicer-mcp-test-"));
});
after(async () => {
  await rm(dir, { recursive: true, force: true });
});

test("variants: quoted when they hold spaces, read back either way", () => {
  assert.equal(escapeVariants(["HF0.4", "HT Hotend 0.4", "0.6"]), 'HF0.4;"HT Hotend 0.4";0.6');
  assert.deepEqual(parseVariants('HF0.4;"HT Hotend 0.4";0.6'), ["HF0.4", "HT Hotend 0.4", "0.6"]);
  assert.deepEqual(parseVariants("HF0.4; HF0.6"), ["HF0.4", "HF0.6"]);
  assert.deepEqual(parseVariants('"a \\"b\\""'), ['a "b"']);
});

test("installed state from PrusaSlicer.ini", () => {
  const installed = parseInstalled(APP_INI);
  assert.deepEqual([...installed.filaments], ["Generic PETG @COREONE HF0.4", "Prusament PLA @COREONE HF0.4"]);
  assert.deepEqual(installed.vendors.get("PrusaResearch")?.get("COREONE"), ["HF0.4"]);
});

test("writing changes only the owned sections, in place", () => {
  const wanted = parseInstalled(APP_INI);
  wanted.filaments.add("Buddy3D PETG @COREONE HF0.4");
  wanted.vendors.get("PrusaResearch")!.set("COREONE", ["HF0.4", "HT Hotend 0.4"]);
  wanted.vendors.get("PrusaResearch")!.set("MK4S", ["HF0.4"]);
  wanted.vendors.set("Creality", new Map([["ENDER3", ["0.4"]]]));
  const next = writeInstalled(APP_INI, wanted);

  assert.deepEqual(parseInstalled(next), wanted);
  // Untouched lines and order stay; [filaments] stays before [presets].
  assert.ok(next.startsWith("# generated by PrusaSlicer 2.9.7"));
  assert.ok(next.indexOf("[filaments]") < next.indexOf("[presets]"));
  assert.ok(next.includes("[presets]\nfilament = Generic PETG @COREONE HF0.4\nprinter = Prusa CORE One HF0.4 nozzle\n"));
  assert.ok(next.includes('model:COREONE = HF0.4;"HT Hotend 0.4"\nmodel:MK4S = HF0.4'));
  assert.ok(next.trimEnd().endsWith("[vendor:Creality]\nmodel:ENDER3 = 0.4"));
  // Sorted, and never a duplicate key: PrusaSlicer rejects the whole file for one.
  const filaments = next.split("[filaments]\n")[1]!.split("\n\n")[0]!.split("\n");
  assert.deepEqual(filaments, [...filaments].sort());
  assert.equal(new Set(filaments).size, filaments.length);
});

test("nothing changes when nothing is asked", () => {
  assert.equal(writeInstalled(APP_INI, parseInstalled(APP_INI)), APP_INI);
});

test("removing the last filament drops the section; the Windows checksum line is dropped", () => {
  const wanted = parseInstalled(APP_INI);
  wanted.filaments.clear();
  const next = writeInstalled(`${APP_INI}# MD5 checksum 0123456789ABCDEF0123456789ABCDEF\n`, wanted);
  assert.ok(!next.includes("[filaments]"));
  assert.ok(!next.includes("MD5 checksum"));
  assert.ok(next.includes("[vendor:PrusaResearch]"));
});

test("bundles: filaments without abstract parents, models with variants", async () => {
  await mkdir(join(dir, "vendor"));
  await writeFile(
    join(dir, "vendor", "PrusaResearch.ini"),
    [
      "[vendor]",
      "name = Prusa Research",
      "[printer_model:COREONE]",
      "name = Prusa CORE One",
      "variants = HF0.4; HF0.6; HT Hotend 0.4",
      "technology = FFF",
      "[filament:*PETG*]",
      "filament_type = PETG",
      "[filament:Buddy3D PETG @COREONE HF0.4]",
      "inherits = *PETG*",
      "",
    ].join("\n"),
  );
  const [bundle] = await readBundles(dir);
  assert.equal(bundle!.vendorId, "PrusaResearch");
  assert.equal(bundle!.name, "Prusa Research");
  assert.deepEqual([...bundle!.filaments], ["Buddy3D PETG @COREONE HF0.4"]);
  assert.deepEqual(bundle!.models.get("COREONE")?.variants, ["HF0.4", "HF0.6", "HT Hotend 0.4"]);
});
