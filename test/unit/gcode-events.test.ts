import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { analyzeAsciiGcode } from "../../src/formats/gcode-ascii.ts";

// The lines around a pause with a message, custom G-code and a template, as each version wrote them
// for a 20 mm cube (2026-11-25). Only the markers and a few moves are kept.
const ALPHA15 = `; generated by PrusaSlicer 3.0.0-alpha15 on 2026-11-25 at 15:40:01 UTC

;LAYER_CHANGE
;Z:5
;HEIGHT:0.2
;PAUSE_PRINT
;PAUSE_PRINT_MESSAGE:Swap the magnets
M117 Swap the magnets
M601
G1 X10 Y10 E.5
;LAYER_CHANGE
;Z:10
;HEIGHT:0.2
;CUSTOM_GCODE
;CUSTOM_GCODE_START
M117 hello
G4 S1
;CUSTOM_GCODE_END
G1 Z10 F720
;LAYER_CHANGE
;Z:15
;HEIGHT:0.2
;CUSTOM_GCODE
;CUSTOM_TEMPLATE_START

;CUSTOM_TEMPLATE_END
G1 Z15 F720
`;

const V297 = `; generated by PrusaSlicer 2.9.7 on 2026-11-25 at 15:42:10 UTC

;LAYER_CHANGE
;Z:5
;HEIGHT:0.2
;PAUSE_PRINT
M117 Swap the magnets
M601
G1 X10 Y10 E.5
;LAYER_CHANGE
;Z:10
;HEIGHT:0.2
;CUSTOM_GCODE
M117 hello
G4 S1
G1 Z10 F720
;LAYER_CHANGE
;Z:15
;HEIGHT:0.2
;CUSTOM_GCODE
G1 Z15 F720
`;

async function eventsOf(text: string) {
  const dir = await mkdtemp(join(tmpdir(), "psmcp-gcode-"));
  try {
    const path = join(dir, "part.gcode");
    await writeFile(path, text);
    return (await analyzeAsciiGcode(path)).events.map(({ kind, z, message, gcode, template }) => ({ kind, z, message, gcode, template }));
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

test("3.0.0-alpha15: the pause's message, the custom G-code's lines and the template", async () => {
  assert.deepEqual(await eventsOf(ALPHA15), [
    { kind: "pause", z: 5, message: "Swap the magnets", gcode: undefined, template: undefined },
    { kind: "custom", z: 10, message: undefined, gcode: "M117 hello\nG4 S1", template: undefined },
    { kind: "custom", z: 15, message: undefined, gcode: undefined, template: true },
  ]);
});

test("2.9.7: the pause's message from its M117; custom G-code without an end marker has no lines", async () => {
  assert.deepEqual(await eventsOf(V297), [
    { kind: "pause", z: 5, message: "Swap the magnets", gcode: undefined, template: undefined },
    { kind: "custom", z: 10, message: undefined, gcode: undefined, template: undefined },
    { kind: "custom", z: 15, message: undefined, gcode: undefined, template: undefined },
  ]);
});

test("an M601 in custom G-code still counts as a pause; an M117 outside a pause is no message", async () => {
  const text = `;LAYER_CHANGE\n;Z:2\nM117 Printing\n;CUSTOM_GCODE\n;CUSTOM_GCODE_START\nM601\n;CUSTOM_GCODE_END\nM600\n`;
  assert.deepEqual(await eventsOf(text), [
    { kind: "custom", z: 2, message: undefined, gcode: "M601", template: undefined },
    { kind: "pause", z: 2, message: undefined, gcode: undefined, template: undefined },
    { kind: "color_change", z: 2, message: undefined, gcode: undefined, template: undefined },
  ]);
});
