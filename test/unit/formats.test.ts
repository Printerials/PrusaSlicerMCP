import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { test } from "node:test";
import { readGcode, durationSeconds } from "../../src/formats/gcode.ts";
import { parseHelp, parseHelpFff } from "../../src/formats/help.ts";
import { parseInfo } from "../../src/formats/info.ts";
import { parseCommentedConfig, parseIniConfig, parseIniSections, splitList, unescapeValue } from "../../src/formats/ini.ts";

const fixtures = join(import.meta.dirname, "..", "fixtures");

test("--help: version and the options this binary accepts", async () => {
  const help = parseHelp(await readFile(join(fixtures, "help-2.9.7.txt"), "utf8"));
  assert.equal(help.version, "2.9.7");
  assert.equal(help.major, 2);
  assert.ok(help.options.has("export-gcode"));
  assert.ok(help.options.has("query-print-filament-profiles"));
  assert.ok(help.options.has("single-instance"));
  assert.ok(!help.options.has("query-print-tool-filament-profiles"));
});

test("--help: prerelease versions", () => {
  assert.equal(parseHelp("PrusaSlicer-3.0.0-alpha14 based on Slic3r").version, "3.0.0-alpha14");
});

test("--help-fff: catalogue with types, units, values and defaults", async () => {
  const entries = parseHelpFff(await readFile(join(fixtures, "help-fff-2.9.7.txt"), "utf8"));
  const byKey = new Map(entries.map((entry) => [entry.key, entry]));
  // 368 print settings in 2.9.7, after the general CLI options.
  assert.ok(entries.length > 350, `only ${entries.length} entries`);

  const pattern = byKey.get("fill_pattern")!;
  assert.equal(pattern.category, "Infill");
  assert.equal(pattern.type, "enum");
  assert.equal(pattern.default, "stars");
  assert.ok(pattern.values?.includes("gyroid"));
  assert.ok(!pattern.description.includes("default:"));

  const layer = byKey.get("layer_height")!;
  assert.equal(layer.type, "number");
  assert.equal(layer.unit, "mm");
  assert.equal(layer.default, "0.3");

  // One space between metavar and description: " --bed-temperature N Bed temperature..."
  assert.equal(byKey.get("bed_temperature")?.type, "number");
  assert.equal(byKey.get("bed_temperature")?.unit, "°C");
  assert.equal(byKey.get("support_material")?.type, "bool");
  // Per-extruder vectors have no metavar in the help, but a default that is not a flag.
  assert.equal(byKey.get("filament_seam_gap_distance")?.type, "list");
  assert.ok(byKey.has("binary_gcode"));
  assert.ok(byKey.has("post_process"));
});

test("--info: one entry per file", async () => {
  const [model] = parseInfo(await readFile(join(fixtures, "info-cube.txt"), "utf8"));
  assert.deepEqual(model!.size, [20, 20, 20]);
  assert.equal(model!.volume, 8000);
  assert.equal(model!.facets, 12);
  assert.equal(model!.parts, 1);
  assert.equal(model!.manifold, true);
});

test("INI: sections, commented configs, escapes and lists", () => {
  const sections = parseIniSections("[presets]\nprinter = Prusa CORE One HF0.4 nozzle\n\n[recent_projects]\n1 = /a/b.3mf\n");
  assert.equal(sections.get("presets")?.get("printer"), "Prusa CORE One HF0.4 nozzle");
  assert.equal(sections.get("recent_projects")?.get("1"), "/a/b.3mf");

  const saved = parseIniConfig("# generated by PrusaSlicer\nlayer_height = 0.2\npost_process = \n");
  assert.equal(saved.get("layer_height"), "0.2");
  assert.equal(saved.get("post_process"), "");

  const commented = parseCommentedConfig("; filament used [mm] = 12.5\n; estimated printing time (normal mode) = 1h 2m\nG1 X1\n");
  assert.equal(commented.get("filament used [mm]"), "12.5");
  assert.equal(commented.get("estimated printing time (normal mode)"), "1h 2m");

  assert.equal(unescapeValue("M600\\nG1 E0.3 F1500 ; prime"), "M600\nG1 E0.3 F1500 ; prime");
  assert.deepEqual(splitList('"Prusament PLA";"Generic PETG"'), ["Prusament PLA", "Generic PETG"]);
  assert.deepEqual(splitList("0.4,0.6"), ["0.4", "0.6"]);
});

test("durations", () => {
  assert.equal(durationSeconds("15m 23s"), 923);
  assert.equal(durationSeconds("1d 2h 3m 4s"), 93784);
});

test("ASCII G-code: summary, layers, features, config", async () => {
  const { report, config } = await readGcode(join(fixtures, "cube5.gcode"));
  assert.equal(report.format, "ascii");
  assert.equal(report.generator, "PrusaSlicer 2.9.7");
  assert.equal(report.printer_model, "COREONE");
  assert.equal(report.presets.print, "0.20mm SPEED @COREONE HF0.4");
  assert.deepEqual(report.presets.filament, ["Prusament PLA @COREONE HF0.4"]);
  assert.ok(report.time.normal_seconds! > 0);
  assert.ok(report.filament.total_g! > 0);
  assert.equal(report.layers.count, 25);
  assert.equal(report.layers.max_z, 5);
  assert.deepEqual(report.layers.heights, [0.2]);
  assert.ok(report.features!.some((feature) => feature.type === "External perimeter"));
  assert.equal(config.get("pause_print_gcode"), "M601");
  assert.deepEqual(report.objects, ["cube.stl"]);
});

test("binary G-code: metadata and the same summary", async () => {
  const ascii = (await readGcode(join(fixtures, "cube5.gcode"))).report;
  const { report, config } = await readGcode(join(fixtures, "cube5.bgcode"));
  assert.equal(report.format, "binary");
  assert.equal(report.printer_model, "COREONE");
  assert.equal(report.time.normal, ascii.time.normal);
  assert.equal(report.filament.total_g, ascii.filament.total_g);
  assert.equal(report.presets.printer, "Prusa CORE One HF0.4 nozzle");
  assert.equal(config.get("layer_height"), "0.2");
  assert.equal(report.layers.max_z, 5);
});
